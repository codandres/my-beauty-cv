import { readdirSync, writeFileSync } from 'node:fs';
import { z } from 'zod';
import { languageFromPath } from '../src/content/files';
import { CvSchema } from '../src/schema/cv.schema';
import { settingsSchema } from '../src/schema/settings.schema';

// Editor-facing JSON Schemas: autocomplete and validation while editing the files in data/.
const dataDir = new URL('../data/', import.meta.url);
const languages = readdirSync(dataDir).flatMap((file) => languageFromPath(file) ?? []);

function write(file: string, schema: z.ZodType, purpose: string) {
  const json = {
    $comment: `GENERATED by \`npm run schema\` from src/schema/: edits here are overwritten. ${purpose}`,
    ...z.toJSONSchema(schema, { io: 'input' }),
  };
  writeFileSync(new URL(file, dataDir), `${JSON.stringify(json, null, 2)}\n`);
  console.log(`Wrote data/${file}`);
}

write('cv.schema.json', CvSchema, 'Validates data/cv.<language>.json.');
write(
  'settings.schema.json',
  settingsSchema(languages),
  'Pick the template and language in data/settings.json.',
);
